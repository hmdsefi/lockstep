// The marker lines around the block of README.md that budget readme writes.
const (
	readmeBegin = "<!-- begin: generated by budget readme from bench/results/baseline.txt -->"
	readmeEnd   = "<!-- end: generated by budget readme -->"
)

// readmeIntro is the sentence above the README table.
const readmeIntro = "Lower is better in every row."

// commitURL is the prefix of the link to the commit that the baseline measured.
const commitURL = "https://github.com/hmdsefi/lockstep/commit/"

// libTitles holds the header of each library's column in the README table.
var libTitles = map[string]string{
	"lockstep":   "lockstep",
	"protoactor": "protoactor-go",
	"hollywood":  "Hollywood",
	"goakt":      "GoAkt",
}

// headline is one row of the README table: a lockstep result and the same result of each other
// library.
type headline struct {
	// label names the workload and its parameter.
	label string
	// name is the lockstep benchmark, from which counterpart gives the other libraries'.
	name string
	// unit is the unit of the medians in the baseline.
	unit string
	// what says what one value measures. A time value shows ns or µs in front of it.
	what string
	// count is the number of items one op handles when the row shows the median per item, such as
	// the actors that one op of BenchmarkIdleActors spawns, and 0 when it shows the median as it is.
	count float64
}

// headlines lists the rows of the README table, in order.
var headlines = []headline{
	{"Ping-pong, 1 pair", "BenchmarkPingPong/lib=lockstep/pairs=1", "ns/op", "per message", 0},
	{"Ping-pong, `GOMAXPROCS` pairs", "BenchmarkPingPong/lib=lockstep/pairs=procs", "ns/op", "per message", 0},
	{"Fan-out to 1,024 consumers", "BenchmarkFanOut/lib=lockstep/consumers=1024", "ns/op", "per item", 0},
	{"100,000 idle actors", "BenchmarkIdleActors/lib=lockstep/n=100000", "B/actor", "heap bytes per actor", 0},
	// The median ns/op divided by 100,000, not the median ns/actor, so that the row follows from
	// the ns/op table of RESULTS.md, which has no ns/actor table.
	{"Spawning 100,000 idle actors", "BenchmarkIdleActors/lib=lockstep/n=100000", "ns/op", "per actor", 100000},
	{"Send latency, p50", "BenchmarkSendLatency/lib=lockstep", "p50-ns", "", 0},
	{"Send latency, p99", "BenchmarkSendLatency/lib=lockstep", "p99-ns", "", 0},
	{"Ask latency, 1 caller, p50", "BenchmarkAskLatency/lib=lockstep/callers=1", "p50-ns", "", 0},
	{"Ask latency, 1 caller, p99", "BenchmarkAskLatency/lib=lockstep/callers=1", "p99-ns", "", 0},
	{"Ping-pong, 1 pair", "BenchmarkPingPong/lib=lockstep/pairs=1", "allocs/op", "allocations per message", 0},
}

// commitHash matches the value of the # commit: line, a hexadecimal commit hash of at least seven
// digits.
var commitHash = regexp.MustCompile(`^[0-9a-f]{7,64}$`)

// microsFrom is the smallest value, in nanoseconds, of every cell of a row that the README table
// shows in microseconds.
const microsFrom = 10000

// readmeCommand runs budget readme. It reads the baseline and the Markdown file named by args, and
// replaces the lines between the marker lines of the Markdown file with the table for the
// baseline. It changes nothing when the baseline or the Markdown file is malformed.
func readmeCommand(args []string, stderr io.Writer) int {
	flags := flag.NewFlagSet("readme", flag.ContinueOnError)
	if code, done := parseFlags(flags, args, stderr); done {
		return code
	}
	switch flags.NArg() {
	case 0:
		return usageError(stderr, "missing baseline file")
	case 1:
		return usageError(stderr, "missing README file")
	case 2:
	default:
		return usageError(stderr, "too many files")
	}
	baselineFile, readmeFile := flags.Arg(0), flags.Arg(1)
	res, err := readResults([]string{baselineFile})
	if err != nil {
		return inputError(stderr, err)
	}
	block, err := readmeTable(baselineFile, res)
	if err != nil {
		return inputError(stderr, err)
	}
	data, err := os.ReadFile(readmeFile)
	if err != nil {
		return inputError(stderr, err)
	}
	text, err := replaceBlock(readmeFile, string(data), block)
	if err != nil {
		return inputError(stderr, err)
	}
	if text != string(data) {
		// The file exists, so WriteFile keeps its permissions.
		if err := os.WriteFile(readmeFile, []byte(text), 0o600); err != nil {
			return inputError(stderr, err)
		}
	}
	return 0
}

// readmeTable builds the block of README.md for the baseline in res, read from file: a sentence,
// the table with a row for each headline and a column for each library, and a paragraph that
// names the commit, date and CPU of the run. A cell is the median rounded for reading, and
// noResult marks a library with no result. The baseline must have the lockstep result of every
// headline and the # commit:, # date: and cpu: lines.
func readmeTable(file string, res *results) (string, error) {
	header := "| Result |"
	for _, lib := range libs {
		header += " " + libTitles[lib] + " |"
	}
	text := []string{header, "|---" + strings.Repeat("|---:", len(libs)) + "|"}
	for _, h := range headlines {
		row, err := headlineRow(res, h)
		if err != nil {
			return "", fmt.Errorf("%s: %w", file, err)
		}
		text = append(text, row)
	}

	commit, err := requiredValue(file, res.comments, "commit", "# commit:")
	if err != nil {
		return "", err
	}
	if !commitHash.MatchString(commit) {
		return "", fmt.Errorf("%s: # commit: %s is not a hexadecimal commit hash", file, commit)
	}
	date, err := requiredValue(file, res.comments, "date", "# date:")
	if err != nil {
		return "", err
	}
	cpu, err := requiredValue(file, res.config, "cpu", "cpu:")
	if err != nil {
		return "", err
	}
	footer := fmt.Sprintf("Each number comes from a median of the run in [`bench/results/baseline.txt`](bench/results/baseline.txt): "+
		"commit [`%s`](%s%s), measured on %s with the CPU `%s`. "+
		"[`bench/RESULTS.md`](bench/RESULTS.md) has more results of that run, library by library.",
		commit[:7], commitURL, commit, date, cpu)

	return strings.Join([]string{readmeIntro, strings.Join(text, "\n"), footer}, "\n\n"), nil
}

// requiredValue returns the first value of key in kv, the header lines of the baseline read from
// file. A missing or empty value is an error that names the line, given as line.
func requiredValue(file string, kv []config, key, line string) (string, error) {
	if v, ok := firstValue(kv, key); ok && v != "" {
		return v, nil
	}
	return "", fmt.Errorf("%s: no %s line", file, line)
}

// headlineRow returns the row of the README table for h. A value is the median, divided by
// h.count when h.count is not 0. A time shows in microseconds, with one decimal, when every value
// of the row is at least microsFrom nanoseconds, and otherwise in whole nanoseconds; both round
// half away from zero. Another unit shows the value as report prints a median. Every value has
// commas between its groups of three digits.
func headlineRow(res *results, h headline) (string, error) {
	medians := map[string]float64{}
	for _, lib := range libs {
		s := series{counterpart(h.name, lib), h.unit}
		m, ok := res.median(s)
		if !ok {
			if lib == "lockstep" {
				return "", fmt.Errorf("no result for %s %s", s.name, s.unit)
			}
			continue
		}
		if m < 0 {
			return "", fmt.Errorf("%s %s has median %s, want a non-negative number", s.name, s.unit, formatMedian(m))
		}
		if h.count != 0 {
			m /= h.count
		}
		medians[lib] = m
	}

	isTime := strings.HasPrefix(h.unit, "ns/") || strings.HasSuffix(h.unit, "-ns")
	micros := isTime
	for _, m := range medians {
		micros = micros && m >= microsFrom
	}
	unit := h.what
	if isTime {
		unit = "ns"
		if micros {
			unit = "µs"
		}
		if h.what != "" {
			unit += " " + h.what
		}
	}

	row := []string{h.label + " (" + unit + ")"}
	for _, lib := range libs {
		m, ok := medians[lib]
		switch {
		case !ok:
			row = append(row, noResult)
		case micros:
			row = append(row, groupThousands(strconv.FormatFloat(math.Round(m/100)/10, 'f', 1, 64)))
		case isTime:
			row = append(row, groupThousands(formatFloat(math.Round(m))))
		default:
			row = append(row, groupThousands(formatMedian(m)))
		}
	}
	return "| " + strings.Join(row, " | ") + " |", nil
}

// groupThousands puts a comma between the groups of three digits in the integer part of s, a
// non-negative decimal number: 1234567.5 gives 1,234,567.5.
func groupThousands(s string) string {
	whole, fraction, hasFraction := strings.Cut(s, ".")
	var b strings.Builder
	for i, c := range whole {
		if i > 0 && (len(whole)-i)%3 == 0 {
			b.WriteByte(',')
		}
		b.WriteRune(c)
	}
	if hasFraction {
		b.WriteString("." + fraction)
	}
	return b.String()
}

// replaceBlock returns text, the contents of the Markdown file named file, with the lines between
// the marker lines readmeBegin and readmeEnd replaced by block, which a blank line separates from
// each marker. text must have each marker line once, readmeBegin first.
func replaceBlock(file, text, block string) (string, error) {
	var lines []string
	for line := range strings.Lines(text) {
		lines = append(lines, line)
	}
	begin, end := -1, -1
	for i, line := range lines {
		switch strings.TrimRight(line, "\r\n") {
		case readmeBegin:
			if begin >= 0 {
				return "", markerError(file)
			}
			begin = i
		case readmeEnd:
			if end >= 0 {
				return "", markerError(file)
			}
			end = i
		}
	}
	if begin < 0 || end < begin {
		return "", markerError(file)
	}
	return strings.Join(lines[:begin+1], "") + "\n" + block + "\n\n" + strings.Join(lines[end:], ""), nil
}

// markerError is the error of a Markdown file whose marker lines are missing, repeated or out of
// order.
func markerError(file string) error {
	return errors.New(file + ": want the line " + readmeBegin + " once, and the line " + readmeEnd + " once after it")
}
