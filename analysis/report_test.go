// TestReporter checks the reporter (ANL-080, ANL-110, ANL-120): suppression by the directive
// index for suppressible IDs only, the generated-file filter, deduplication on position, ID and
// message, the chain suffix, the category, and the order by file name and offset, stable for one
// position.
func TestReporter(t *testing.T) {
	// The file set holds z.go before a.go, so position order differs from file name order.
	sources := []struct{ name, src string }{
		{"z.go", "package p\n\nvar z = 1\n"},
		{"a.go", "package p\n\nvar a = 1 //lockstep:allow LS100 test\n\nvar b = 2\n"},
		{"gen.go", "// Code generated by hand. DO NOT EDIT.\n\npackage p\n\nvar g = 1\n"},
	}
	fset := token.NewFileSet()
	var files []*ast.File
	contents := map[string][]byte{}
	for _, s := range sources {
		f, err := parser.ParseFile(fset, s.name, s.src, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		files = append(files, f)
		contents[s.name] = []byte(s.src)
	}
	line := func(file string, n int) token.Pos {
		for _, f := range files {
			if tf := fset.File(f.Pos()); tf.Name() == file {
				return tf.LineStart(n)
			}
		}
		t.Fatalf("no file %s", file)
		return token.NoPos
	}
	var got []analysis.Diagnostic
	pass := &analysis.Pass{
		Fset:     fset,
		Files:    files,
		Report:   func(d analysis.Diagnostic) { got = append(got, d) },
		ReadFile: func(name string) ([]byte, error) { return contents[name], nil },
		// runIndex reads the facts of imported packages and exports its own; there are none.
		AllObjectFacts:   func() []analysis.ObjectFact { return nil },
		ExportObjectFact: func(types.Object, analysis.Fact) {},
	}
	res, err := runIndex(pass)
	if err != nil {
		t.Fatal(err)
	}
	idx, ok := res.(*directiveIndex)
	if !ok {
		t.Fatalf("runIndex returned %T", res)
	}
	z, a, b, g := line("z.go", 3), line("a.go", 3), line("a.go", 5), line("gen.go", 5)

	add := func(r *reporter) {
		r.reportActor(b, "LS100", "late", "(*A).Receive")
		r.report(z, "LS110", "in z")
		r.report(a, "LS100", "suppressed")
		r.report(a, "LS110", "second check")
		r.report(a, "LS001", "not suppressible")
		r.report(a, "LS110", "second check")
		r.report(g, "LS100", "generated")
		r.flush()
	}
	type diag struct {
		pos           token.Pos
		category, msg string
	}
	summary := func(ds []analysis.Diagnostic) []diag {
		var out []diag
		for _, d := range ds {
			out = append(out, diag{d.Pos, d.Category, d.Message})
		}
		return out
	}

	add(newReporter(pass, idx))
	want := []diag{
		{a, "LS110", "LS110: second check"},
		{a, "LS001", "LS001: not suppressible"},
		{b, "LS100", "LS100: late (actor code: (*A).Receive)"},
		{z, "LS110", "LS110: in z"},
	}
	if s := summary(got); !slices.Equal(s, want) {
		t.Errorf("with the index:\n got %v\nwant %v", fmt.Sprint(s), fmt.Sprint(want))
	}

	got = nil
	add(newReporter(pass, nil))
	want = slices.Insert(want, 0, diag{a, "LS100", "LS100: suppressed"})
	if s := summary(got); !slices.Equal(s, want) {
		t.Errorf("without the index:\n got %v\nwant %v", fmt.Sprint(s), fmt.Sprint(want))
	}
}
